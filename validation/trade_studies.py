"""Phase 7: classical trade studies, every point a fully re-sized aircraft.

Writes ``docs/figures/trades.png``, ``docs/figures/trades_carpet.png`` and
``validation/results/trades.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from acdesign import plotting as P
from acdesign.constraint_analysis import constraint_diagram
from acdesign.external.engine import CFM56_7B26, LEAP_1B28, Engine
from acdesign.requirements import B737_800_MISSION as M
from acdesign.sizing import Design, size_aircraft
from acdesign.trade_studies import aspect_ratio, bypass_ratio, carpet, cruise_altitude
from acdesign.units import FT

RESULTS = Path(__file__).resolve().parent / "results"
ALTITUDES = np.arange(29000, 41001, 2000) * FT
WS = np.linspace(5000.0, 7000.0, 9)
TW = np.linspace(0.25, 0.35, 9)


def _panel(ax, pts, base, xlabel, title, scale=1.0):
    x = [p.value * scale for p in pts]
    ax.plot(
        x,
        [100 * (p.W0 / base.W0 - 1) for p in pts],
        "o-",
        ms=4,
        color=P.SERIES[0],
        label="take-off mass",
    )  # noqa: E501
    ax.plot(
        x,
        [100 * (p.fuel / base.fuel_mass - 1) for p in pts],
        "s-",
        ms=4,
        color=P.SERIES[1],
        label="mission fuel",
    )  # noqa: E501
    ax.plot(
        x,
        [100 * (p.oew / base.oew - 1) for p in pts],
        "^-",
        ms=4,
        color=P.SERIES[2],
        label="empty mass",
    )  # noqa: E501
    ax.axhline(0, color=P.TEXT_MUTED, lw=0.8)
    ax.set_xlabel(xlabel)
    ax.set_ylabel("change from the baseline [%]")
    ax.set_title(title)


def figure(base, ar, bpr, alt):
    P.use_style()
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.2))
    _panel(axes[0], ar, base, "wing aspect ratio", "Aspect ratio")
    _panel(axes[1], bpr, base, "bypass ratio (CFM56-7B core technology)", "Bypass ratio")
    _panel(
        axes[2], alt, base, "initial cruise altitude [FL]", "Cruise altitude", scale=1 / FT / 100
    )  # noqa: E501
    axes[0].legend()
    fig.tight_layout()
    return P.save(fig, "trades.png")


def figure_carpet(base, W0, fuel):
    P.use_style()
    fig, ax = plt.subplots(figsize=(7.5, 5))
    cs = ax.contour(WS, TW, W0 / 1e3, levels=12, colors=P.SERIES[0], linewidths=1.0)
    ax.clabel(cs, fmt="%.1f t", fontsize=7)
    cf = ax.contour(
        WS, TW, fuel / 1e3, levels=8, colors=P.SERIES[1], linewidths=0.8, linestyles="--"
    )  # noqa: E501
    ax.clabel(cf, fmt="%.1f t fuel", fontsize=7)
    d = constraint_diagram(M, base.polar, Engine(base.design.engine))
    ax.plot(d.ws, d.envelope, color=P.TEXT, lw=1.6, label="T/W envelope (baseline polar)")
    ax.axvline(d.ws_limit, color=P.TEXT, lw=1.6, ls="-.", label="landing field length")
    ax.plot(base.ws, base.tw, "o", color=P.TEXT, ms=8, label="design point")
    ok = ~np.isnan(W0)
    feas = np.array([[d.feasible(w, t) for w in WS] for t in TW]) & ok
    i, j = np.unravel_index(np.nanargmin(np.where(feas, W0, np.nan)), W0.shape)
    ax.plot(WS[j], TW[i], "*", color=P.SERIES[3], ms=14, label="lightest feasible grid point")
    ax.set_xlim(WS[0], WS[-1])
    ax.set_ylim(TW[0], TW[-1])
    ax.set_xlabel("wing loading W/S [Pa]")
    ax.set_ylabel("thrust loading T/W")
    ax.set_title("Carpet: take-off mass (solid) and fuel (dashed)")
    ax.legend(fontsize=7.5, loc="lower right", frameon=True, facecolor=P.SURFACE, framealpha=0.95)
    return P.save(fig, "trades_carpet.png"), (WS[j], TW[i], W0[i, j])


def write_results(base, ar, bpr, alt, leap, best):
    def table(pts, label, fmt):
        rows = [
            f"| {fmt(p.value)} | {p.W0:,.0f} | {p.oew:,.0f} | {p.fuel:,.0f} | {p.S:.1f} | "
            f"{p.thrust / 1e3:.1f} | {p.LD:.2f} | {p.tsfc * 1e6:.2f} | {p.active} |"
            for p in pts
        ]
        return [
            f"| {label} | W0 [kg] | OEW [kg] | fuel [kg] | S [m²] | T [kN] | L/D | TSFC [mg/(N s)] | sets T/W |",  # noqa: E501
            "|---|---|---|---|---|---|---|---|---|",
            *rows,
            "",
        ]

    lines = [
        "# Trade studies",
        "",
        "Generated by `validation/trade_studies.py`. Baseline: the sized design "
        f"(A = {base.design.AR}, CFM56-7B26/3, FL350): W0 {base.W0:,.0f} kg, fuel "
        f"{base.fuel_mass:,.0f} kg.",
        "",
        "## Aspect ratio",
        "",
        *table(ar, "A", lambda v: f"{v:.0f}"),
        "## Bypass ratio (rubber engines of the CFM56-7B26/3 core technology)",
        "",
        *table(bpr, "BPR", lambda v: f"{v:g}"),
        "## The two calibrated engines (AERO-03)",
        "",
        "| engine | W0 [kg] | fuel [kg] | fuel vs CFM56-7B26/3 |",
        "|---|---|---|---|",
        f"| CFM56-7B26/3 | {base.W0:,.0f} | {base.fuel_mass:,.0f} | |",
        f"| LEAP-1B28 | {leap.W0:,.0f} | {leap.fuel_mass:,.0f} | {leap.fuel_mass / base.fuel_mass - 1:+.1%} |",  # noqa: E501
        "",
        "## Initial cruise altitude",
        "",
        *table(alt, "FL", lambda v: f"{v / FT / 100:.0f}"),
        "## Carpet",
        "",
        f"Lightest feasible point of the {len(WS)} x {len(TW)} grid: W/S {best[0]:,.0f} Pa, "
        f"T/W {best[1]:.3f}, W0 {best[2]:,.0f} kg; the constraint design point "
        f"({base.ws:,.0f} Pa, {base.tw:.3f}) sizes to {base.W0:,.0f} kg.",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "trades.md").write_text("\n".join(lines))


if __name__ == "__main__":
    base = size_aircraft(M)
    ar = aspect_ratio(M)
    bpr = bypass_ratio(M)
    alt = cruise_altitude(M, ALTITUDES)
    leap = size_aircraft(M, Design(engine=LEAP_1B28))
    assert base.design.engine == CFM56_7B26
    print(figure(base, ar, bpr, alt))
    W0, fuel = carpet(M, WS, TW)
    path, best = figure_carpet(base, W0, fuel)
    print(path)
    write_results(base, ar, bpr, alt, leap, best)
