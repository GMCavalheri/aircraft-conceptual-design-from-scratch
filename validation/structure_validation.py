"""Phase 5: the wing box of the sized design (and of the 737-800 geometry) against the
class II statistical wing mass.

Writes ``docs/figures/structure_wing_box.png`` and ``validation/results/structure.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt

from acdesign import plotting as P
from acdesign.requirements import B737_800_MISSION as M
from acdesign.sizing import size_aircraft
from acdesign.structural_sizing_check import ULTIMATE_LOAD_FACTOR, BoxAssumptions, wing_box
from acdesign.weight_estimation import component_masses

from reference import b737_800
from reference_aircraft import class_two_inputs, geometry

RESULTS = Path(__file__).resolve().parent / "results"
R = b737_800()


def boxes():
    a = size_aircraft(M)
    m = a.masses
    sized = wing_box(
        a.geometry.wing, a.geometry.fuselage_diameter, a.W0, a.W0 - a.fuel_mass, a.fuel_mass,
        m["wing"], (m["engines"] + m["nacelles"]) / 2,
    )  # fmt: skip
    mr = component_masses(class_two_inputs())
    ref = wing_box(
        geometry().wing, R["fuselage_diameter"], R["mtow"], R["mzfw"], R["usable_fuel"],
        mr["wing"], (mr["engines"] + mr["nacelles"]) / 2,
    )  # fmt: skip
    return a, sized, m["wing"], ref, mr["wing"]


def figure(sized):
    P.use_style()
    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    y = sized.y
    axes[0].plot(y, sized.moment / 1e6, color=P.SERIES[0], label="bending moment [MN m]")
    axes[0].plot(y, sized.shear / 1e5, color=P.SERIES[1], label="shear [100 kN]")
    axes[0].set_title(f"Ultimate loads (n = {ULTIMATE_LOAD_FACTOR})")
    axes[0].set_xlabel("span station y [m]")
    axes[0].legend()
    axes[1].plot(y, sized.t_upper * 1e3, color=P.SERIES[0], label="upper cover (7075-T6)")
    axes[1].plot(y, sized.t_lower * 1e3, color=P.SERIES[1], label="lower cover (2024-T3)")
    axes[1].plot(y, sized.t_web * 1e3, color=P.SERIES[2], label="spar webs (7075-T6)")
    switch = next(i for i, g in enumerate(sized.upper_governed_by) if g != "column")
    axes[1].axvline(y[switch], color=P.TEXT_MUTED, lw=1, ls=":")
    axes[1].text(y[switch] + 0.2, 2.6, "skin buckling\ngoverns outboard", fontsize=8,
                 color=P.TEXT_MUTED)  # fmt: skip
    axes[1].set_title("Smeared thicknesses")
    axes[1].set_xlabel("span station y [m]")
    axes[1].set_ylabel("[mm]")
    axes[1].legend()
    axes[2].plot(y, sized.height, color=P.SERIES[0], label="box height")
    axes[2].plot(y, sized.width, color=P.SERIES[1], label="box width (normal to the spar)")
    axes[2].set_title("Box dimensions [m]")
    axes[2].set_xlabel("span station y [m]")
    axes[2].legend()
    fig.tight_layout()
    return P.save(fig, "structure_wing_box.png")


def _fmt(v):
    return f"{v:,.0f}" if abs(v) >= 100 else f"{v:.3g}"


def write_results(a, sized, c2, ref, c2_ref):
    asm = BoxAssumptions()
    rows = [
        ("ideal box, both wings [kg]", sized.box_mass, ref.box_mass),
        (
            f"x non-optimum {asm.non_optimum} + {asm.secondary_areal_mass:g} kg/m² secondary [kg]",
            sized.wing_mass,
            ref.wing_mass,
        ),  # noqa: E501
        ("class II wing (Raymer) [kg]", c2, c2_ref),
        ("physics / statistics", sized.wing_mass / c2, ref.wing_mass / c2_ref),
        ("root bending moment, ultimate [MN m]", sized.root_moment / 1e6, ref.root_moment / 1e6),
        ("1-g tip deflection [m]", sized.tip_deflection_1g, ref.tip_deflection_1g),
        (
            "1-g tip deflection / semispan",
            sized.tip_deflection_1g / (a.geometry.wing.b / 2),
            ref.tip_deflection_1g / (geometry().wing.b / 2),
        ),  # noqa: E501
    ]
    lines = [
        "# Structural sizing check",
        "",
        "Generated by `validation/structure_validation.py`.",
        "",
        f"Allowables (MIL-HDBK-5J B-basis via AERO-02): upper cover {sized.sigma_upper / 1e6:.0f} MPa "  # noqa: E501
        f"(Johnson column, rib pitch {asm.rib_pitch} m); lower cover {sized.sigma_lower / 1e6:.0f} MPa "  # noqa: E501
        f"(governed by {sized.lower_governed_by}: the Kt = 2 ground-air-ground curve does not bind).",  # noqa: E501
        "",
        "| | sized design | 737-800 geometry |",
        "|---|---|---|",
        *[f"| {n} | {_fmt(s)} | {_fmt(r)} |" for n, s, r in rows],
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "structure.md").write_text("\n".join(lines))


if __name__ == "__main__":
    a, sized, c2, ref, c2_ref = boxes()
    print(figure(sized))
    write_results(a, sized, c2, ref, c2_ref)
