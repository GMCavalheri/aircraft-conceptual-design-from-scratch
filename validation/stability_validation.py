"""Phase 6b: static margin and dynamic modes of the sized aircraft at mid-cruise, against
MIL-F-8785C Level 1 (Class III, category B).

Writes ``docs/figures/stability_modes.png`` and ``validation/results/stability.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from acdesign import plotting as P
from acdesign.external import stability as fd
from acdesign.performance_verification import flying_qualities, modes, stability_model
from acdesign.requirements import B737_800_MISSION as M
from acdesign.sizing import size_aircraft

RESULTS = Path(__file__).resolve().parent / "results"


def figure(model, mo):
    P.use_style()
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    ax = axes[0]
    for k, (name, mode) in enumerate(
        [
            ("short period", mo.short_period),
            ("phugoid", mo.phugoid),
            ("dutch roll", mo.dutch_roll),
            ("roll", mo.roll),
            ("spiral", mo.spiral),
        ]  # fmt: skip
    ):
        ev = np.atleast_1d(mode.eigenvalues)
        ax.plot(ev.real, ev.imag, "x", color=P.SERIES[k], ms=9, mew=2, label=name)
    w = np.linspace(0, 2.5, 50)
    for zeta, ls in [(0.08, ":"), (0.30, "-.")]:
        x = -zeta / np.sqrt(1 - zeta**2) * w
        ax.plot(x, w, color=P.TEXT_MUTED, lw=0.9, ls=ls, label=f"ζ = {zeta} (Level 1 minimum)")
    ax.axvline(-0.15, color=P.SERIES[2], lw=0.8, ls="--", label="ζω = 0.15 (dutch roll)")
    ax.set_xlabel("real part [1/s]")
    ax.set_ylabel("imaginary part [rad/s]")
    ax.set_title("Mid-cruise roots of the sized design (bare airframe)")
    ax.set_xlim(-2.0, 0.1)
    ax.set_ylim(-0.5, 2.5)
    ax.legend(fontsize=7.5, loc="upper left")

    ax = axes[1]
    dh = np.linspace(-0.25, model.static_margin + 0.02, 31)
    sm, zeta = [], []
    for d in dh:
        ac = fd.move_cg(model.aircraft, d)
        sm.append(fd.neutral_point_shift(ac))
        try:
            t = fd.trim(ac, model.V, model.h)
        except RuntimeError:  # the solver can stall at an exact start; nudge the guess
            t = fd.trim(ac, model.V, model.h, guess=np.array([0.01, 0, 0, 0.01, 0, 0, 0.2]))
        lon = fd.longitudinal_modes(fd.longitudinal(fd.linearize(ac, t)).A)
        zeta.append(lon["short_period"].zeta if lon["short_period"].is_oscillatory else np.nan)
    x = 100 * (model.balance.h_cg + dh)
    ax.plot(x, 100 * np.array(sm), color=P.SERIES[0], label="static margin [% MAC]")
    ax2 = ax.twinx()
    ax2.plot(x, zeta, color=P.SERIES[1], label="short-period damping")
    ax2.set_ylabel("short-period damping ζ", color=P.SERIES[1])
    ax2.grid(False)
    ax.axvline(100 * model.balance.h_cg, color=P.TEXT_MUTED, lw=1, ls=":")
    ax.set_xlabel("CG position [% MAC]")
    ax.set_ylabel("static margin [% MAC]", color=P.SERIES[0])
    ax.set_title(f"CG travel: neutral point at {100 * model.h_n_classic:.0f} % MAC (textbook)")
    fig.tight_layout()
    return P.save(fig, "stability_modes.png")


def write_results(model, mo):
    fq = flying_qualities(mo)
    d = model.aircraft.aero
    rows = [f"| {k} | {v:.3g} | {'met' if ok else '**not met**'} |" for k, (v, ok) in fq.items()]
    names = [
        "CL_a",
        "Cm_a",
        "Cm_q",
        "Cm_adot",
        "Cm_de",
        "CY_b",
        "Cl_b",
        "Cn_b",
        "Cl_p",
        "Cn_p",
        "Cl_r",
        "Cn_r",
        "Cl_da",
        "Cn_dr",
    ]  # noqa: E501
    lines = [
        "# Stability verification",
        "",
        "Generated by `validation/stability_validation.py`. Mid-cruise (FL350, Mach 0.78, "
        f"{model.balance.mass:,.0f} kg), CG at {100 * model.balance.h_cg:.0f} % MAC "
        f"(empty: {100 * model.balance.h_cg_oew:.0f} %).",
        "",
        "## Static stability",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| wing aerodynamic centre (VLM, Mach 0.78) | {100 * model.h_ac_wing:.1f} % MAC |",
        f"| wing-body aerodynamic centre (Torenbeek fuselage shift) | {100 * model.h_ac_wb:.1f} % MAC |",  # noqa: E501
        f"| downwash gradient at the tail (VLM) | {model.eps_a:.3f} |",
        f"| wing / tail lift slopes (VLM, Göthert) | {model.a_wb:.2f} / {model.a_t:.2f} per rad |",
        f"| neutral point, textbook formula | {100 * model.h_n_classic:.1f} % MAC |",
        f"| static margin, AERO-04 neutral_point_shift | **{100 * model.static_margin:.1f} % MAC** |",  # noqa: E501
        "",
        "## Derivatives (stability axes, per rad)",
        "",
        "| " + " | ".join(names) + " |",
        "|" + "---|" * len(names),
        "| " + " | ".join(f"{getattr(d, n):.3f}" for n in names) + " |",
        "",
        "## Modes against MIL-F-8785C Level 1 (Class III, category B)",
        "",
        "| requirement | value | |",
        "|---|---|---|",
        *rows,
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "stability.md").write_text("\n".join(lines))


if __name__ == "__main__":
    model = stability_model(size_aircraft(M))
    mo = modes(model)
    print(figure(model, mo))
    write_results(model, mo)
