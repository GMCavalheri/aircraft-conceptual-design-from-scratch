"""Phase 3: the constraint diagram of the design mission, with the 737-800 on it.

First-estimate polar (Raymer, ch. 12): CD0 = C_fe S_wet/S_ref from the reference geometry's
wetted areas, Oswald e from Raymer's fit. Writes ``docs/figures/constraint_diagram.png`` and
``validation/results/constraints.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from acdesign import plotting as P
from acdesign.constraint_analysis import (
    DragPolar,
    cd0_equivalent_skin_friction,
    constraint_diagram,
    oswald_raymer,
)
from acdesign.external.engine import Engine
from acdesign.external.wing_aero import Planform
from acdesign.requirements import B737_800_MISSION as M
from acdesign.units import G0, LBF

from reference import b737_800
from reference_aircraft import wetted_areas

RESULTS = Path(__file__).resolve().parent / "results"
R = b737_800()


def reference_polar() -> DragPolar:
    wing = Planform(
        R["wing_area"], R["wing_aspect_ratio"], R["wing_taper_ratio"], R["wing_sweep_quarter_chord"]
    )
    ratio = sum(wetted_areas().values()) / R["wing_area"]
    return DragPolar(
        CD0=cd0_equivalent_skin_friction(ratio),
        e=oswald_raymer(wing.AR, wing.sweep_at(0.0)),
        AR=wing.AR,
    )


def reference_point() -> tuple[float, float, float]:
    """737-800 at MTOW: W/S [Pa], T/W with the ICAO-rated CFM56-7B26/3 and with the
    26,000 lbf rating of the field-length chart."""
    W = R["mtow"] * G0
    return W / R["wing_area"], 2 * 117.0e3 / W, 2 * 26000 * LBF / W


def figure(d):
    P.use_style()
    fig, ax = plt.subplots(figsize=(8, 5))
    for k, (name, tw) in enumerate(d.tw.items()):
        ax.plot(d.ws, tw, color=P.SERIES[k], lw=1.6, label=name)
    for k, (name, ws) in enumerate(d.ws_max.items()):
        ax.axvline(ws, color=P.SERIES[len(d.tw) + k], lw=1.6, label=name)
    ok = d.ws <= d.ws_limit
    ax.fill_between(d.ws[ok], d.envelope[ok], 0.5, color=P.SERIES[2], alpha=0.08, lw=0)
    ws, tw = d.design
    ax.plot(ws, tw, "o", color=P.TEXT, ms=8, label=f"design point ({ws:,.0f} Pa, {tw:.3f})")
    rws, rtw, _ = reference_point()
    ax.plot(rws, rtw, "D", color=P.REFERENCE, mfc="none", ms=8, label="737-800 (MTOW, 117 kN)")
    ax.set_xlim(d.ws[0], d.ws[-1])
    ax.set_ylim(0.15, 0.42)
    ax.set_xlabel("wing loading W/S at take-off [Pa]")
    ax.set_ylabel("thrust loading T/W (sea-level static)")
    ax.set_title("Constraint diagram, design mission (first-estimate polar)")
    ax.legend(fontsize=7.5, loc="upper left", ncol=2)
    return P.save(fig, "constraint_diagram.png")


def write_results(d, polar):
    ws, tw = d.design
    rws, rtw, rtw26 = reference_point()
    rows = [f"| {k} | {np.interp(ws, d.ws, v):.4f} |" for k, v in d.tw.items()]
    rows += [f"| {k} (max W/S) | {v:,.0f} Pa |" for k, v in d.ws_max.items()]
    lines = [
        "# Constraint analysis",
        "",
        "Generated by `validation/constraint_validation.py`. First-estimate polar: "
        f"CD0 = {polar.CD0:.5f} (C_fe = 0.0026), e = {polar.e:.3f}, A = {polar.AR:.2f}; "
        f"CLmax take-off {polar.takeoff.CLmax}, landing {polar.landing.CLmax} (assumptions).",
        "",
        "## Requirements at the design wing loading",
        "",
        "| requirement | T/W |",
        "|---|---|",
        *rows,
        "",
        "## Design point against the 737-800",
        "",
        "| | W/S [Pa] | T/W |",
        "|---|---|---|",
        f"| design point ({d.active(ws)} sets T/W) | {ws:,.0f} | {tw:.4f} |",
        f"| 737-800 at MTOW, CFM56-7B26/3 117 kN (ICAO) | {rws:,.0f} | {rtw:.4f} |",
        f"| 737-800 at MTOW, 26,000 lbf (field-length chart) | {rws:,.0f} | {rtw26:.4f} |",
        f"| model / 737-800 | {ws / rws - 1:+.1%} | {tw / rtw - 1:+.1%} |",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "constraints.md").write_text("\n".join(lines))


if __name__ == "__main__":
    polar = reference_polar()
    d = constraint_diagram(M, polar, Engine())
    print(figure(d))
    write_results(d, polar)
