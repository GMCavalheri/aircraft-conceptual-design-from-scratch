"""Phase 2: class I sizing of the design mission and class II weights of the 737-800.

Writes ``docs/figures/weights_class_one.png``, ``docs/figures/weights_class_two.png`` and
``validation/results/weights.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

from acdesign import plotting as P
from acdesign.external.atmosphere import isa
from acdesign.external.engine import Engine
from acdesign.requirements import B737_800_MISSION as M
from acdesign.units import FT, LB
from acdesign.weight_estimation import (
    component_masses,
    empty_mass,
    group_masses,
    max_lift_to_drag,
    operating_empty_mass,
    size_class_one,
)
from acdesign.weight_estimation.class_two import GROUPS

from reference import b737_800
from reference_aircraft import class_two_inputs, crew_mass, wetted_areas

RESULTS = Path(__file__).resolve().parent / "results"
R = b737_800()
HOLD = (1500 * FT, 0.40, 15e3)  # hold point (altitude, Mach, thrust per engine): assumption
CRUISE_THRUST = 22e3  # per engine, for the class I cruise TSFC: assumption (~W/(2 L/D))


def class_one():
    S_wet = sum(wetted_areas().values())
    LD = max_lift_to_drag(R["wing_aspect_ratio"], S_wet / R["wing_area"])
    e = Engine()
    V = M.cruise_mach * float(isa(M.cruise_altitude).a)
    tc = e.tsfc(M.cruise_altitude, M.cruise_mach, CRUISE_THRUST)
    th = e.tsfc(*HOLD)
    res = size_class_one(M, V, LD, tc, th, crew=crew_mass())
    return res, {"S_wet/S_ref": S_wet / R["wing_area"], "(L/D)max": LD, "V": V, "tsfc": tc}


def figure_class_one(res):
    P.use_style()
    fig, ax = plt.subplots(figsize=(6.5, 3.8))
    h = np.array(res.history) / 1e3
    ax.plot(range(len(h)), h, "o-", color=P.SERIES[0], ms=4, label="class I iteration")
    ax.axhline(R["mtow"] / 1e3, color=P.REFERENCE, ls="--", lw=1.2, label="737-800 MTOW")
    ax.set_xlabel("iteration")
    ax.set_ylabel("take-off mass W0 [t]")
    ax.set_title("Class I sizing converges in a dozen steps")
    ax.legend()
    return P.save(fig, "weights_class_one.png")


def figure_class_two(masses):
    P.use_style()
    fig, ax = plt.subplots(figsize=(7.5, 6.0))
    names, values, colors = [], [], []
    for k, keys in enumerate(GROUPS.values()):
        for key in keys:
            names.append(f"{key.replace('_', ' ')}")
            values.append(masses[key] / 1e3)
            colors.append(P.SERIES[k])
    y = np.arange(len(names))[::-1]
    ax.barh(y, values, color=colors, height=0.7)
    ax.set_yticks(y, names)
    handles = [Patch(color=P.SERIES[k], label=g.replace("_", " ")) for k, g in enumerate(GROUPS)]
    ax.set_xlabel("mass [t]")
    oew = operating_empty_mass(masses)
    ax.set_title(f"Class II, 737-800 geometry: OEW {oew / 1e3:.1f} t vs {R['oew'] / 1e3:.1f} t")
    ax.legend(handles=handles, loc="lower right")
    return P.save(fig, "weights_class_two.png")


def write_results(res, info, masses):
    g = group_masses(masses)
    oew = operating_empty_mass(masses)
    lines = [
        "# Weight estimation",
        "",
        "Generated by `validation/weight_validation.py`.",
        "",
        "## Class I, design mission (160 pax, 2,800 nmi)",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| S_wet/S_ref (reference geometry) | {info['S_wet/S_ref']:.2f} |",
        f"| (L/D)max, wetted aspect ratio | {info['(L/D)max']:.2f} |",
        f"| cruise L/D (0.866 (L/D)max) | {0.866 * info['(L/D)max']:.2f} |",
        f"| cruise TSFC (AERO-03 engine, 22 kN, FL350 M0.78) | {info['tsfc'] * 1e6:.2f} mg/(N s) |",
        f"| fuel fraction Wf/W0 | {res.fractions.fuel:.4f} (trip {res.fractions.trip:.4f}) |",
        f"| empty fraction We/W0 | {res.empty_fraction:.4f} |",
        f"| **W0** | **{res.W0:,.0f} kg** ({res.W0 / LB:,.0f} lb) |",
        f"| 737-800 MTOW | {R['mtow']:,.0f} kg; model {res.W0 / R['mtow'] - 1:+.1%} |",
        "",
        "## Class II, 737-800 geometry at MTOW (no calibration)",
        "",
        "| group | mass [kg] |",
        "|---|---|",
        *[f"| {k.replace('_', ' ')} | {v:,.0f} |" for k, v in g.items()],
        f"| empty (structure + propulsion + systems) | {empty_mass(masses):,.0f} |",
        f"| **OEW** | **{oew:,.0f}** |",
        f"| 737-800 OEW (D6-58325-7 2.1.3) | {R['oew']:,.0f}; model {oew / R['oew'] - 1:+.1%} |",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "weights.md").write_text("\n".join(lines))


if __name__ == "__main__":
    res, info = class_one()
    masses = component_masses(class_two_inputs())
    print(figure_class_one(res))
    print(figure_class_two(masses))
    write_results(res, info, masses)
