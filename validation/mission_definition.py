"""Phase 1: the design mission against the 737-800's payload-range envelope.

Writes ``docs/figures/mission_payload_range.png`` and ``validation/results/mission.md``.
The envelope is drawn through the corners read from D6-58325-7 3.2.4 (chart readings, see
``reference_data/b737_800.csv`` for their resolution).
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt

from acdesign import plotting as P
from acdesign.requirements import B737_800_MISSION as M
from acdesign.units import FT, LB, NMI

from reference import b737_800

RESULTS = Path(__file__).resolve().parent / "results"


def envelope(R):
    """(range [nmi], payload [lb]) corners of the MTOW payload-range envelope."""
    max_pl = R["max_structural_payload"] / LB
    corner_pl = (R["oew_plus_payload_at_full_fuel_mtow"] - R["oew"]) / LB
    r = [0.0, R["range_at_mzfw_mtow"], R["range_at_full_fuel_mtow"]]
    r += [R["range_at_full_fuel_zero_payload"]]
    return [x / NMI for x in r], [max_pl, max_pl, corner_pl, 0.0]


def figure(R):
    P.use_style()
    fig, ax = plt.subplots(figsize=(7.5, 4.2))
    x, y = envelope(R)
    ref = "737-800, MTOW 174,200 lb (D6-58325-7 3.2.4, read)"
    ax.plot(x, [v / 1e3 for v in y], color=P.REFERENCE, lw=1.4, ls="--", label=ref)
    design = f"design mission: {M.passengers} pax × 225 lb, {M.design_range / NMI:,.0f} nmi"
    ax.plot(M.design_range / NMI, M.payload / LB / 1e3, "o", color=P.SERIES[1], label=design)
    ax.set_xlabel("range [nmi]")
    ax.set_ylabel("payload [1,000 lb]")
    ax.set_title("Design mission and the reference payload-range envelope")
    ax.set_xlim(0, 4000)
    ax.set_ylim(0, 55)
    ax.legend(loc="lower left")
    return P.save(fig, "mission_payload_range.png")


def write_results(R):
    rows = [
        ("passengers (two-class)", f"{M.passengers}", "data, D6-58325-7 2.1.3"),
        ("payload", f"{M.payload / LB:,.0f} lb ({M.payload:,.0f} kg)", "assumption: 225 lb/pax"),
        ("design range", f"{M.design_range / NMI:,.0f} nmi", "requirement (assumption)"),
        ("cruise", f"Mach {M.cruise_mach}, FL{M.cruise_altitude / FT / 100:.0f}", "assumption"),
        ("take-off field length", f"{M.takeoff_field_length / FT:,.0f} ft", "data, 3.3.29 (chart)"),
        ("landing field length", f"{M.landing_field_length / FT:,.0f} ft", "data, 3.4.3 (chart)"),
        ("MLW / MTOW", f"{M.landing_weight_ratio:.3f}", "deduction, 2.1.3"),
        ("reserves", "5 % trip + 200 nmi + 30 min at 1,500 ft", "assumption"),
    ]
    lines = [
        "# Design mission",
        "",
        "Generated by `validation/mission_definition.py`.",
        "",
        "| requirement | value | label |",
        "|---|---|---|",
        *[f"| {a} | {b} | {c} |" for a, b, c in rows],
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "mission.md").write_text("\n".join(lines))


if __name__ == "__main__":
    R = b737_800()
    print(figure(R))
    write_results(R)
