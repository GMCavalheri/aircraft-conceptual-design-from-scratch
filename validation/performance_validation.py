"""Phase 6a: the sized aircraft flown through its mission, and its payload-range diagram
against the 737-800's.

Tank capacity of the sized design (deduction): the 737-800's 26,024 L scaled with wing
area^1.5 (geometrically similar tanks); its maximum payload is the 737-800's (same
fuselage). Writes ``docs/figures/performance_payload_range.png`` and
``validation/results/performance.md``.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt

from acdesign import plotting as P
from acdesign.performance_verification import design_range, payload_range
from acdesign.requirements import B737_800_MISSION as M
from acdesign.sizing import FUEL_DENSITY, size_aircraft
from acdesign.units import LB, NMI

from mission_definition import envelope
from reference import b737_800

RESULTS = Path(__file__).resolve().parent / "results"
R = b737_800()


def capacity(a) -> float:
    """Fuel capacity [kg] of the sized design: 737-800 tanks scaled with S^1.5."""
    return 26.024 * 1000 * FUEL_DENSITY * (a.S / R["wing_area"]) ** 1.5


def figure(corners):
    P.use_style()
    fig, ax = plt.subplots(figsize=(7.5, 4.2))
    x, y = envelope(R)
    ax.plot(
        x,
        [v / 1e3 for v in y],
        color=P.REFERENCE,
        lw=1.4,
        ls="--",
        label="737-800 (D6-58325-7 3.2.4, read)",
    )  # noqa: E501
    ax.plot(
        [c[0] for c in corners],
        [c[1] / LB / 1e3 for c in corners],
        "o-",
        color=P.SERIES[0],
        ms=4,
        label="sized design (integrated mission)",
    )  # noqa: E501
    ax.plot(
        M.design_range / NMI, M.payload / LB / 1e3, "o", color=P.SERIES[1], label="design mission"
    )  # noqa: E501
    ax.set_xlabel("range [nmi]")
    ax.set_ylabel("payload [1,000 lb]")
    ax.set_title("Payload-range: sized design and the 737-800")
    ax.set_xlim(0, 4500)
    ax.set_ylim(0, 55)
    ax.legend(loc="lower left")
    return P.save(fig, "performance_payload_range.png")


def write_results(a, r, corners, cap):
    seg = [
        f"| {s.name} | {s.distance / NMI:,.0f} | {s.fuel:,.0f} | {s.time / 60:,.0f} |"
        for s in r.segments
    ]  # noqa: E501
    lines = [
        "# Performance verification",
        "",
        "Generated by `validation/performance_validation.py`.",
        "",
        "## Design mission flown with the sized fuel load",
        "",
        "| segment | distance [nmi] | fuel [kg] | time [min] |",
        "|---|---|---|---|",
        *seg,
        f"| reserves (held) | | {r.reserve_fuel:,.0f} | |",
        f"| **total** | **{r.range / NMI:,.0f}** (requirement {M.design_range / NMI:,.0f}) | "
        f"**{a.fuel_mass:,.0f}** (incl. 1 % trapped) | |",
        "",
        f"Breguet sizing vs integration: {r.range / M.design_range - 1:+.1%} range on the same fuel.",  # noqa: E501
        "",
        "## Fuel volume and payload-range",
        "",
        f"Design fuel {a.fuel_mass:,.0f} kg = {a.fuel_mass / FUEL_DENSITY:,.0f} L; capacity "
        f"(737-800 tanks scaled with S^1.5) {cap:,.0f} kg = {a.fuel_mass / cap:.0%} of it. "
        + (
            "The design fuel fits."
            if a.fuel_mass <= cap
            else f"It does **not** fit: {(a.fuel_mass - cap) / FUEL_DENSITY:,.0f} L more are "
            "needed — the landing-limited wing is too small to hold the design fuel in "
            "similarly scaled tanks (a larger centre tank, or a larger wing, would fix it)."
        ),
        "",
        "| corner | range [nmi] | payload [kg] |",
        "|---|---|---|",
        *[
            f"| {n} | {c[0]:,.0f} | {c[1]:,.0f} |"
            for n, c in zip(
                (
                    "max payload, zero range",
                    "max payload at MTOW",
                    "full tanks at MTOW",
                    "full tanks, zero payload",
                ),
                corners,
                strict=True,
            )
        ],  # noqa: E501
        "",
        f"737-800 (chart): max payload to {R['range_at_mzfw_mtow'] / NMI:,.0f} nmi, full tanks at "
        f"MTOW {R['range_at_full_fuel_mtow'] / NMI:,.0f} nmi, ferry {R['range_at_full_fuel_zero_payload'] / NMI:,.0f} nmi.",  # noqa: E501
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "performance.md").write_text("\n".join(lines))


if __name__ == "__main__":
    a = size_aircraft(M)
    r = design_range(a)
    cap = capacity(a)
    corners = payload_range(a, R["max_structural_payload"], cap)
    print(figure(corners))
    write_results(a, r, corners, cap)
